#!/usr/bin/env python3
"""Centrality tables written before out-degree and in-degree were named by their regulatory
meaning hold the targets of a TF under in_centrality and its regulators under out_centrality
(the network function stores the edge of entry [i, j] as (j, i) and read the out-degree of that
graph). The function now exchanges the two assignments and leaves the graph and every other
centrality as they were, so its output is the old table with the values of the two columns
exchanged. This script does that for the tables of the benchmark conditions (pseudobulk, scVI,
the scRNA-seq reproduction run and GRNBoost2), keeping the old files in
results/_superseded_20261002_degree. The tables of notebook 12 itself are regenerated by the
notebook (regenerate_notebook12.py).
"""
import os, glob, shutil
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'results', 'exp14_conditions')
KEEP = os.path.join(HERE, 'results', '_superseded_20261002_degree')
os.makedirs(KEEP, exist_ok=True)
files = sorted(glob.glob(os.path.join(SRC, '*TF_GRN_centrality_t?-t?_zscore3.csv')))
for f in files:
    keep = os.path.join(KEEP, os.path.basename(f))
    if not os.path.exists(keep):
        shutil.copy2(f, keep)
    old = pd.read_csv(keep, index_col=0)                 # always start from the old table
    new = old.copy()
    outs = [c for c in old.columns if c.endswith('_out_centrality')]
    assert len(outs) == 10, (f, len(outs))
    for c in outs:
        d = c.replace('_out_centrality', '_in_centrality')
        new[c], new[d] = old[d], old[c]
    new.to_csv(f, index=True)
    print(os.path.basename(f), new.shape)
print(len(files), 'tables')
